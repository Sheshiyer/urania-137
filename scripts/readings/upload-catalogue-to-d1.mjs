#!/usr/bin/env node
/**
 * Upload 723 corpus catalogue metadata to the D1 database (urania-137-db) for
 * the corpus data browser (T-079, ISC-#139).
 *
 * Reads the manifest inventory from the 723 corpus directory, generates INSERT
 * statements for the `catalogue_readings` table with ON CONFLICT DO NOTHING
 * for idempotency, and executes them via `wrangler d1 execute`.
 *
 * Dry-run by default (prints generated SQL + summary). Use --apply to execute.
 *
 * Usage:
 *   node scripts/readings/upload-catalogue-to-r1.mjs \
 *     --corpus-root <absolute-path-to-723> \
 *     --owner-email <email> \
 *     --confirm-owner-consent \
 *     --user-id <uuid> \
 *     [--apply] [--dry-run] [--report <file>]
 *
 * Requires the owner's D1 user_id (from the `users` table) to scope rows.
 * Requires CLOUDFLARE_ACCOUNT_ID in env for --apply.
 */

import { writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'
import { randomUUID } from 'node:crypto'
import { buildArchiveInventory } from './lib/archive-import.mjs'

const USAGE = `Usage:
  node scripts/readings/upload-catalogue-to-d1.mjs \\
    --corpus-root <723-dir> \\
    --owner-email <email> \\
    --user-id <uuid> \\
    --confirm-owner-consent \\
    [--apply] [--dry-run] [--report <file>]

Generates and optionally executes INSERT statements for catalogue_readings (53 rows).
--user-id is the owner's D1 user UUID (from the users table).
Dry-run by default; use --apply to execute via wrangler d1 execute.
`

function parseOperatorArgs(args) {
  return parseArgs({
    args,
    allowPositionals: false,
    strict: true,
    options: {
      'corpus-root': { type: 'string' },
      'owner-email': { type: 'string' },
      'user-id': { type: 'string' },
      'confirm-owner-consent': { type: 'boolean', default: false },
      apply: { type: 'boolean', default: false },
      'dry-run': { type: 'boolean', default: false },
      report: { type: 'string' },
      help: { type: 'boolean', short: 'h', default: false },
    },
  }).values
}

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i

function validateUserId(value) {
  if (!value) throw new Error('--user-id is required')
  if (!UUID_RE.test(value)) {
    throw new Error('--user-id must be a valid UUID (from the users table)')
  }
  return value
}

export function buildD1UpsertSql(inventory, userId) {
  const nowSec = Math.floor(Date.now() / 1000)
  const rows = inventory.units.map((unit) => {
    const id = randomUUID()
    const sha256 = unit.artifact.contentSha256
    const title = unit.title
    const mode = unit.readingType === 'synastry' ? 'Synastry' : 'Solo'
    const sourceType = 'integrated-kundali-l0'
    const isSynastry = unit.readingType === 'synastry' ? 1 : 0
    const r2Key = `corpus/readings/${sha256}/reading.html`
    const canonicalUri = unit.source.corpusRelativePath
      ? `723/${unit.source.corpusRelativePath}`
      : null

    const sqlEscape = (s) => `'${String(s).replace(/'/g, "''")}'`

    return {
      id,
      userId,
      sha256,
      title: sqlEscape(title),
      mode: sqlEscape(mode),
      sourceType: sqlEscape(sourceType),
      createdAt: nowSec,
      isSynastry,
      canonicalUri: canonicalUri ? sqlEscape(canonicalUri) : 'NULL',
      r2Key: sqlEscape(r2Key),
    }
  })

  const inserts = rows.map((r) =>
    `('${r.id}', '${r.userId}', '${r.sha256}', ${r.title}, ${r.mode}, ${r.sourceType}, ${r.createdAt}, ${r.isSynastry}, ${r.canonicalUri}, ${r.r2Key})`,
  )

  const valuesClause = inserts.join(',\n  ')

  return `-- Generated by scripts/readings/upload-catalogue-to-d1.mjs
-- Schema: migration 0009_catalogue_readings
-- Owner: ${inventory.ownerEmail} (sha256: ${inventory.ownerEmailSha256})
-- Consent: ${inventory.consentBasis}
-- Manifest: ${inventory.manifestId}
-- Rows: ${rows.length} (${inventory.counts.solo} Solo + ${inventory.counts.synastry} Synastry)
INSERT INTO catalogue_readings (
  id, user_id, sha256, title, mode, source_type, created_at, is_synastry, canonical_uri, r2_key
) VALUES
  ${valuesClause}
ON CONFLICT DO NOTHING;`
}

export async function buildD1Plan(options = {}) {
  const { corpusRoot, ownerEmail, userId } = options

  const inventory = await buildArchiveInventory({ corpusRoot, ownerEmail })

  const sql = buildD1UpsertSql(inventory, userId)

  return {
    schemaVersion: 'd1-catalogue-v1',
    ownerEmail,
    ownerEmailSha256: inventory.ownerEmailSha256,
    userId,
    consentBasis: inventory.consentBasis,
    manifestId: inventory.manifestId,
    manifestSha256: inventory.manifestSha256,
    counts: inventory.counts,
    totals: inventory.totals,
    d1Database: 'urania-137-db',
    d1Table: 'catalogue_readings',
    sql,
    rowCount: inventory.counts.total,
    rows: inventory.units.map((unit) => ({
      sha256: unit.artifact.contentSha256,
      title: unit.title,
      mode: unit.readingType === 'synastry' ? 'Synastry' : 'Solo',
      r2Key: `corpus/readings/${unit.artifact.contentSha256}/reading.html`,
    })),
  }
}

export async function applyToD1(plan, options = {}) {
  const { accountId } = options
  if (!accountId) throw new Error('accountId is required for --apply')

  const { execSync } = await import('node:child_process')

  const tempSqlPath = `/tmp/catalogue-upsert-${Date.now()}.sql`
  await writeFile(tempSqlPath, plan.sql, 'utf8')

  try {
    const cmd = `wrangler d1 execute urania-137-db --file ${tempSqlPath} --remote`
    execSync(cmd, { stdio: 'pipe' })
    return { method: 'wrangler-d1', table: plan.d1Table, rows: plan.rowCount }
  } catch (error) {
    throw new Error(`D1 apply failed: ${error.message}`)
  } finally {
    await import('node:fs/promises').then((fs) => fs.rm(tempSqlPath, { force: true }).catch(() => {}))
  }
}

export async function serializeD1Plan(plan) {
  return JSON.stringify({
    schemaVersion: plan.schemaVersion,
    owner: {
      emailSha256: plan.ownerEmailSha256,
      consentBasis: plan.consentBasis,
    },
    userId: plan.userId,
    manifestId: plan.manifestId,
    manifestSha256: plan.manifestSha256,
    counts: plan.counts,
    totals: plan.totals,
    d1Database: plan.d1Database,
    d1Table: plan.d1Table,
    rowCount: plan.rowCount,
    keyPattern: 'catalogue_readings',
  }, null, 2)
}

async function main(args = process.argv.slice(2), env = process.env) {
  const values = parseOperatorArgs(args)
  if (values.help) {
    process.stdout.write(USAGE)
    return
  }
  if (!values['corpus-root']) throw new Error('--corpus-root is required')
  if (!values['owner-email']) throw new Error('--owner-email is required')
  validateUserId(values['user-id'])
  if (!values['confirm-owner-consent']) {
    throw new Error('--confirm-owner-consent is required')
  }

  const plan = await buildD1Plan({
    corpusRoot: path.resolve(values['corpus-root']),
    ownerEmail: values['owner-email'],
    userId: values['user-id'],
  })

  if (values['dry-run'] || !values.apply) {
    const summary = await serializeD1Plan(plan)
    if (values.report) {
      await writeFile(path.resolve(values.report), JSON.parse(summary) + '\n', 'utf8')
      process.stderr.write(`Dry-run report written to ${values.report}\n`)
    }
    process.stdout.write(summary + '\n')
    process.stderr.write(`-- SQL preview (use --apply to execute):\n${plan.sql}\n`)
    return
  }

  const result = await applyToD1(plan, {
    accountId: env.CLOUDFLARE_ACCOUNT_ID,
  })
  process.stdout.write(
    JSON.stringify({ status: 'applied', ...result }, null, 2) + '\n'
  )
}

const isMain =
  process.argv[1] &&
  fileURLToPath(import.meta.url) === path.resolve(process.argv[1])

if (isMain) {
  main().catch((error) => {
    process.stderr.write(`D1 catalogue upload refused: ${error.message}\n`)
    process.exitCode = 1
  })
}

export { parseOperatorArgs }
